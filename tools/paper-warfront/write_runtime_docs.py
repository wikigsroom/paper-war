def table(headers,rows):
    rows=[[str(c).replace('|','/').replace('\n',' ') for c in row] for row in rows]
    return '\n'.join(['| '+' | '.join(headers)+' |','| '+' | '.join(['---']*len(headers))+' |']+['| '+' | '.join(row)+' |' for row in rows])+'\n'

